#!/usr/bin/env node
'use strict';
/* Writes js/rail-icons.js: the pictures of the profile rail as data URIs, so they are part of the card's markup and
   do not blink when the page changes (same idea as the navbar icons, see scripts/prebake-nav-icons.js).
   Run again after changing one of the files below:  node scripts/prebake-rail-icons.js */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const FILES = {
  streak: 'assets/images/gamification/streak-mini.svg',
  xp: 'assets/images/gamification/xp-mini.svg',
  liga: 'assets/images/gamification/liga.svg',
  trophy: 'assets/images/gamification/leaderboard-mini.svg',
  medal: 'assets/images/gamification/realizari.svg',
  owl: 'assets/images/avatar-owl.svg'
};
const out = {};
for (const k of Object.keys(FILES)) out[k] = 'data:image/svg+xml;base64,' + fs.readFileSync(path.join(root, FILES[k])).toString('base64');
fs.writeFileSync(path.join(root, 'js/rail-icons.js'), '/* GENERATED by scripts/prebake-rail-icons.js: do not edit by hand. */\nwindow.RAIL_ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('Wrote js/rail-icons.js (' + Object.keys(out).length + ' icons)');
